(function () {
  // Замена onsubmit="return confirm('<%= t(...) %>')" — тот встраивал переведённую строку
  // (может включать пользовательские данные вроде названия категории/позиции) прямо в JS-код
  // инлайн-атрибута, экранированный только под HTML-контекст. Браузер декодирует HTML-сущности
  // в значении атрибута до того, как выполнит его как JS, так что HTML-экранирования одного было
  // недостаточно — оно защищает от выхода за пределы атрибута, но не от разрыва самой JS-строки
  // внутри него. Здесь текст подтверждения читается как обычная строка через data-атрибут и
  // никогда не проходит повторный разбор как код.
  document.addEventListener('submit', function (e) {
    var message = e.target.getAttribute && e.target.getAttribute('data-confirm');
    if (message && !window.confirm(message)) {
      e.preventDefault();
    }
  });
})();
