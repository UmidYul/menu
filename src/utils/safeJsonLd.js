// Готовит JSON к вставке внутрь <script type="application/ld+json">. JSON.stringify сам по себе
// не трогает последовательность "</script>" — а она закрывает тег для HTML-парсера раньше, чем
// браузер успевает понять, что это внутри JSON-строки. Часть полей (название/адрес заведения и
// т.п.) заполняет владелец заведения, поэтому без экранирования это была бы stored XSS,
// исполняющаяся у каждого гостя, открывшего его меню. Экранированная форма — валидный JSON/JS
// escape для "<", на исполнении разворачивается обратно в исходный символ, но сама по себе не
// встречается как сырой "<" в HTML-разметке, поэтому не может закрыть тег раньше времени.
function toSafeJsonLd(data) {
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

module.exports = { toSafeJsonLd };
